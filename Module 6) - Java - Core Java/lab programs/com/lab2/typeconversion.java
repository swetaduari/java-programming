package com.lab2;

public class typeconversion {

	public static void main(String[] args) {
		
		//implict
		int a = 9;
		double b = a; 
		System.out.println(a);  
		System.out.println(b); 
      //explicit
		
		double c = 9.78;
		int d = (int) c; 

		System.out.println(c); 		
		System.out.println(d);    



	}

}
